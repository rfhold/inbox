test('shared mailboxes, send, reply, read state and raw download', async ({page}) => {
  await page.route('**/config.json', route => route.fulfill({json: {faro_url: '', environment: 'test', version: 'test'}}));
  await page.goto('/');
  const suffix = `${Date.now()}${Math.floor(Math.random()*10000)}`;
  const alice = `alice-${suffix}`, bob = `bob-${suffix}`;
  for (const [local, name] of [[alice, 'Synthetic Alice'], [bob, 'Synthetic Bob']]) {
    await page.getByRole('button', {name: 'Create mailbox', exact: true}).click();
    await page.getByLabel('Name', {exact: true}).fill(name);
    await page.getByLabel('Address local part').fill(local);
    await page.getByRole('button', {name: 'Create', exact: true}).click();
    await expect(page.getByRole('button', {name: 'Create', exact: true})).toHaveCount(0);
    await selectMailbox(page, local);
  }
  const bobAddress = await selectMailbox(page, bob);
  const aliceAddress = await selectMailbox(page, alice);
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill(bobAddress);
  await page.getByLabel('Subject', {exact: true}).fill(`Synthetic subject ${suffix}`);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic plaintext body. <b>This is not HTML.</b>');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Message accepted');
  await selectMailbox(page, bob);
  await expect.poll(async () => {await page.getByRole('button', {name: 'Refresh', exact: true}).click(); return page.locator('.message-row').filter({hasText: `Synthetic subject ${suffix}`}).count();}).toBeGreaterThan(0);
  await page.locator('.message-row').filter({hasText: `Synthetic subject ${suffix}`}).click();
  await expect(page.locator('.body')).toContainText('<b>This is not HTML.</b>');
  await page.getByRole('button', {name: 'Mark read', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Mark unread', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Mark unread', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Mark read', exact: true})).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download EML'}).click();
  const eml = await download;
  expect(eml.suggestedFilename()).toBe('message.eml');
  const stream = await eml.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks).toString('utf8')).toContain(`Synthetic subject ${suffix}`);
  await page.getByRole('button', {name: 'Reply', exact: true}).click();
  await expect(page.getByLabel('To', {exact: true})).toHaveValue(aliceAddress);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic reply body');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Message accepted');
  await selectMailbox(page, alice);
  await expect.poll(async () => {await page.getByRole('button', {name: 'Refresh', exact: true}).click(); return page.locator('.message-row').filter({hasText: `Re: Synthetic subject ${suffix}`}).count();}).toBeGreaterThan(0);
  await page.getByRole('button', {name: 'Sent', exact: true}).click();
  await expect(page.locator('.message-row').filter({hasText: `Synthetic subject ${suffix}`})).toBeVisible();
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('real rejection permits explicit correction and discard without unlocking uncertain sends', async ({page}) => {
  await page.route('**/config.json', route => route.fulfill({json: {faro_url: '', environment: 'test', version: 'test'}}));
  const sentKeys: string[] = [];
  page.on('request', request => {
    if (!request.url().endsWith('/inbox.v1.MailService/SubmitMessage')) return;
    const raw = request.postDataBuffer()!;
    sentKeys.push(fromBinary(SubmitMessageRequestSchema, raw.subarray(5, 5 + raw.readUInt32BE(1))).idempotencyKey);
  });
  const local = `reject-${Date.now()}${Math.floor(Math.random()*10000)}`;
  const subject = `Synthetic rejected draft ${local}`;
  await page.goto('/');
  await page.getByRole('button', {name: 'Create mailbox', exact: true}).click();
  await page.getByLabel('Name', {exact: true}).fill('Synthetic Rejection');
  await page.getByLabel('Address local part').fill(local);
  await page.getByRole('button', {name: 'Create', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Create', exact: true})).toHaveCount(0);
  const address = await selectMailbox(page, local);
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill('synthetic-rejected@example.invalid');
  await page.getByLabel('Subject', {exact: true}).fill(subject);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic rejected content stays durable');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByText('The server rejected the entire submission.', {exact: false})).toBeVisible();
  await expect(page.getByLabel('To', {exact: true})).toBeDisabled();
  await page.reload();
  await openDrafts(page);
  await page.getByRole('button', {name: new RegExp(subject)}).click();
  await expect(page.getByRole('button', {name: 'Copy to new draft', exact: true})).toBeVisible();
  expect(sentKeys).toHaveLength(1);
  await page.getByRole('button', {name: 'Copy to new draft', exact: true}).click();
  await expect(page.getByLabel('To', {exact: true})).toBeEnabled();
  await expect(page.getByRole('button', {name: new RegExp(subject)})).toHaveCount(2);
  await page.getByLabel('To', {exact: true}).fill(address);
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Message accepted');
  expect(sentKeys).toHaveLength(2);
  expect(sentKeys[1]).not.toBe(sentKeys[0]);
  await openDrafts(page);
  const original = page.locator('.draft-link').filter({hasText: subject});
  await expect(original).toHaveCount(1);
  await original.click();
  await expect(page.getByLabel('To', {exact: true})).toHaveValue('synthetic-rejected@example.invalid');
  await page.getByRole('button', {name: 'Discard draft', exact: true}).click();
  await expect(original).toHaveCount(0);
  await page.reload();
  await openDrafts(page);
  await expect(page.locator('.draft-link').filter({hasText: subject})).toHaveCount(0);
});

test('rejected retry accepted with a lost response stays locked and delivers only once', async ({page}) => {
  await page.route('**/config.json', route => route.fulfill({json: {faro_url: '', environment: 'test', version: 'test'}}));
  const submitted: ReturnType<typeof fromBinary<typeof SubmitMessageRequestSchema>>[] = [];
  const acceptedIds: string[] = [];
  let retryResponseAborted = false;
  await page.route('**/inbox.v1.MailService/SubmitMessage', async route => {
    const raw = route.request().postDataBuffer()!;
    submitted.push(fromBinary(SubmitMessageRequestSchema, raw.subarray(5, 5 + raw.readUInt32BE(1))));
    const attempt = submitted.length;
    const response = await route.fetch();
    if (attempt > 1) {
      const body = await response.body();
      const result = fromBinary(SubmitMessageResponseSchema, body.subarray(5, 5 + body.readUInt32BE(1)));
      acceptedIds.push(result.submission!.id);
    }
    if (attempt === 2) {await route.abort('failed'); retryResponseAborted = true;}
    else await route.fulfill({response});
  });
  const suffix = `${Date.now()}${Math.floor(Math.random()*10000)}`;
  const sender = `retry-sender-${suffix}`, recipient = `retry-recipient-${suffix}`;
  const subject = `Synthetic rejected then uncertain ${suffix}`;
  async function createMailbox(local: string) {
    await page.getByRole('button', {name: 'Create mailbox', exact: true}).click();
    await page.getByLabel('Name', {exact: true}).fill(`Synthetic ${local}`);
    await page.getByLabel('Address local part').fill(local);
    await page.getByRole('button', {name: 'Create', exact: true}).click();
    await expect(page.getByRole('button', {name: 'Create', exact: true})).toHaveCount(0);
    return selectMailbox(page, local);
  }
  await page.goto('/');
  const senderAddress = await createMailbox(sender);
  const recipientAddress = `${recipient}@${senderAddress.split('@')[1]}`;
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill(recipientAddress);
  await page.getByLabel('Subject', {exact: true}).fill(subject);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic rejected retry must deliver once.');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByText('The server rejected the entire submission.', {exact: false})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Copy to new draft', exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Discard draft', exact: true})).toBeVisible();
  expect(submitted).toHaveLength(1);
  await page.getByRole('button', {name: 'Close', exact: true}).click();
  expect(await createMailbox(recipient)).toBe(recipientAddress);
  await selectMailbox(page, sender);
  await openDrafts(page);
  await page.locator('.draft-link').filter({hasText: subject}).click();
  await page.getByRole('button', {name: 'Retry send safely', exact: true}).click();
  await expect.poll(() => acceptedIds.length, {message: 'The real server must confirm the second attempt before its response is lost'}).toBe(1);
  await expect.poll(() => retryResponseAborted, {message: 'The accepted retry response must actually be aborted'}).toBe(true);
  await expect(page.getByRole('button', {name: 'Retry send safely', exact: true})).toBeEnabled();
  await expect(page.getByText('Submission unconfirmed.', {exact: false})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Copy to new draft', exact: true})).toHaveCount(0);
  await expect(page.getByRole('button', {name: 'Discard draft', exact: true})).toHaveCount(0);
  expect(acceptedIds).toHaveLength(1);
  expect(acceptedIds[0]).toBeTruthy();
  expect(submitted[1]).toEqual(submitted[0]);
  await page.reload();
  await openDrafts(page);
  await page.locator('.draft-link').filter({hasText: subject}).click();
  await expect(page.getByLabel('To', {exact: true})).toHaveValue(recipientAddress);
  await expect(page.getByLabel('Message', {exact: true})).toBeDisabled();
  await expect(page.getByRole('button', {name: 'Copy to new draft', exact: true})).toHaveCount(0);
  await expect(page.getByRole('button', {name: 'Discard draft', exact: true})).toHaveCount(0);
  expect(submitted).toHaveLength(2);
  await page.getByRole('button', {name: 'Retry send safely', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Message accepted');
  expect(submitted).toHaveLength(3);
  expect(submitted[2]).toEqual(submitted[0]);
  expect(acceptedIds).toEqual([acceptedIds[0], acceptedIds[0]]);
  await openDrafts(page);
  await expect(page.locator('.draft-link').filter({hasText: subject})).toHaveCount(0);
  await selectMailbox(page, recipient);
  await page.getByRole('button', {name: 'Inbox', exact: true}).click();
  await expect.poll(async () => {
    await page.getByRole('button', {name: 'Refresh', exact: true}).click();
    return page.locator('.message-row').filter({hasText: subject}).count();
  }).toBe(1);
  await page.locator('.message-row').filter({hasText: subject}).click();
  await expect(page.locator('.body')).toHaveText('Synthetic rejected retry must deliver once.');
});

test('real Compose cached mail and local draft survive offline reload', async ({page, context}) => {
  await page.route('**/config.json', route => route.fulfill({json: {faro_url: '', environment: 'test', version: 'test'}}));
  const local = `offline-${Date.now()}${Math.floor(Math.random()*10000)}`;
  await page.goto('/');
  await expect.poll(async () => (await page.request.get('/sw.js')).status(), {message: 'Rebuild the app image with the production service worker'}).toBe(200);
  await page.evaluate(async () => {await navigator.serviceWorker.ready;});
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true);
  await page.getByRole('button', {name: 'Create mailbox', exact: true}).click();
  await page.getByLabel('Name', {exact: true}).fill('Synthetic Offline');
  await page.getByLabel('Address local part').fill(local);
  await page.getByRole('button', {name: 'Create', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Create', exact: true})).toHaveCount(0);
  const address = await selectMailbox(page, local);
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill(address);
  await page.getByLabel('Subject', {exact: true}).fill(`Synthetic cached mail ${local}`);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic real-server cached plaintext');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Message accepted');
  await expect.poll(async () => {await page.getByRole('button', {name: 'Refresh', exact: true}).click(); return page.locator('.message-row').filter({hasText: local}).count();}).toBeGreaterThan(0);
  await page.locator('.message-row').filter({hasText: local}).click();
  await expect(page.locator('.body')).toHaveText('Synthetic real-server cached plaintext');
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('Subject', {exact: true}).fill(`Synthetic local draft ${local}`);
  await page.getByLabel('To', {exact: true}).fill(address);
  await page.getByLabel('Message', {exact: true}).fill('Synthetic durable offline draft');
  await expect(page.locator('.composer .muted')).toHaveText('Saved on this device');
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('note', {name: 'Mail synchronization'})).toHaveText(/Offline.*cached mail may be stale/);
  await openDrafts(page);
  await page.getByRole('button', {name: new RegExp(`Synthetic local draft ${local}`)}).click();
  await expect(page.getByLabel('Message', {exact: true})).toHaveValue('Synthetic durable offline draft');
  await expect(page.getByRole('button', {name: 'Send message', exact: true})).toBeDisabled();
  await page.getByRole('button', {name: 'Close', exact: true}).click();
  await selectMailbox(page, local);
  await page.locator('.message-row').filter({hasText: local}).click();
  await expect(page.locator('.body')).toHaveText('Synthetic real-server cached plaintext');
  await context.setOffline(false);
  await expect(page.getByRole('note', {name: 'Mail synchronization'})).toHaveText('Up to date');
  await openDrafts(page);
  await page.getByRole('button', {name: new RegExp(`Synthetic local draft ${local}`)}).click();
  await expect(page.getByLabel('Message', {exact: true})).toHaveValue('Synthetic durable offline draft');
});
