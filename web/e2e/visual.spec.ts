import { test, expect } from '@playwright/test';
import { create, fromBinary, toBinary } from '@bufbuild/protobuf';
import { Folder, GetMessageRequestSchema, GetMessageResponseSchema, ListMailboxesResponseSchema, ListMessagesResponseSchema } from '../src/gen/inbox/v1/inbox_pb';
import { grpcFrame, domainReply, domainFields } from './helpers';
import { mockLocalSession } from './helpers';
test.beforeEach(async ({page}) => {await mockLocalSession(page);});

for (const theme of ['light', 'dark'] as const) test(`${theme} mail layout has independent panes and usable mobile navigation`, async ({page}, info) => {
  await page.emulateMedia({colorScheme: theme, reducedMotion: 'reduce'});
  const subjects = ['Project handoff for Monday', 'Notes from the team', 'A quick follow-up', 'Welcome to the shared inbox'];
  const senders = ['alex', 'jordan', 'sam', 'taylor'];
  const entries = Array.from({length: 32}, (_, index) => ({id: `00000000-0000-4000-8000-${String(index).padStart(12, '0')}`, mailboxId: 'synthetic-design', messageId: `synthetic-message-${index}`, folder: Folder.INBOX, fromAddress: `${senders[index % 4]}@inbox.test`, to: ['team@inbox.test'], subject: subjects[index % 4], preview: 'Here are the notes and next steps for our conversation.', isRead: index % 3 === 1, createdAt: new Date(Date.now() - index * 3600000).toISOString()}));
  const body = 'Hi team,\n\nThe handoff is ready for Monday. I’ve collected the notes and next steps so we can pick up where we left off.\n\nPlease take a look when you have a moment, and reply here with any questions.\n\nThanks,\nAlex\n\nSynthetic preview content.';
  await page.route('**/config.json', route => route.fulfill({json: {faro_url: '', environment: 'test', version: 'test'}}));
  await page.route('**/inbox.v1.MailService/*', async route => {
    const method = new URL(route.request().url()).pathname.split('/').pop();
    let payload: Uint8Array;
    if (method === 'ListDomains') payload = domainReply();
    else if (method === 'ListMailboxes') payload = toBinary(ListMailboxesResponseSchema, create(ListMailboxesResponseSchema, {mailboxes: [{...domainFields, id: 'synthetic-design', name: 'Team inbox', localPart: 'team', address: 'team@inbox.test'}]}));
    else if (method === 'ListMessages') payload = toBinary(ListMessagesResponseSchema, create(ListMessagesResponseSchema, {entries}));
    else if (method === 'GetMessage') {
      const data = route.request().postDataBuffer()!;
      const request = fromBinary(GetMessageRequestSchema, data.subarray(5, 5 + data.readUInt32BE(1)));
      const entry = entries.find(item => item.id === request.entryId)!;
      payload = toBinary(GetMessageResponseSchema, create(GetMessageResponseSchema, {message: {entry, textBody: request.entryId === '00000000-0000-4000-8000-000000000001' ? body.repeat(20) : body}}));
    } else return route.abort();
    await route.fulfill({body: grpcFrame(payload), contentType: 'application/grpc-web+proto'});
  });
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto('/');
  await expect(page.locator('.message-row')).toHaveCount(32);
  expect(await page.evaluate(() => matchMedia('(prefers-color-scheme: dark)').matches)).toBe(theme === 'dark');
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).backgroundColor)).toBe(theme === 'dark' ? 'rgb(16, 18, 27)' : 'rgb(244, 245, 250)');
  await page.emulateMedia({colorScheme: theme === 'dark' ? 'light' : 'dark'});
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).backgroundColor)).toBe(theme === 'dark' ? 'rgb(244, 245, 250)' : 'rgb(16, 18, 27)');
  await page.emulateMedia({colorScheme: theme});
  await page.screenshot({path: info.outputPath(`ui-${theme}-desktop-list.png`)});
  await page.locator('.message-row').nth(1).click();
  await expect(page.locator('.body')).toContainText('Synthetic preview content.');
  expect(await page.locator('.list-scroll').evaluate(el => el.scrollHeight > el.clientHeight && getComputedStyle(el).overflowY === 'auto')).toBe(true);
  expect(await page.locator('.detail').evaluate(el => el.scrollHeight > el.clientHeight && getComputedStyle(el).overflowY === 'auto')).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  await page.locator('.message-row').first().click();
  await expect(page.locator('.body')).toHaveText(body);
  const contrast = await page.locator('.message-row:first-child .preview, .sender-line>div>span, .body').evaluateAll(elements => {
    const luminance = (color: string) => {
      const channels = color.match(/[\d.]+/g)!.slice(0, 3).map(value => Number(value) / 255).map(value => value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4);
      return channels[0] * .2126 + channels[1] * .7152 + channels[2] * .0722;
    };
    return elements.map(element => {
      let ancestor: Element | null = element;
      while (ancestor && getComputedStyle(ancestor).backgroundColor === 'rgba(0, 0, 0, 0)') ancestor = ancestor.parentElement;
      const front = luminance(getComputedStyle(element).color);
      const back = luminance(getComputedStyle(ancestor!).backgroundColor);
      return (Math.max(front, back) + .05) / (Math.min(front, back) + .05);
    });
  });
  for (const ratio of contrast) expect(ratio).toBeGreaterThanOrEqual(4.5);
  await page.screenshot({path: info.outputPath(`ui-${theme}-desktop-detail.png`)});
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill('alex@inbox.test');
  await page.getByLabel('Subject', {exact: true}).fill('Following up');
  await page.getByLabel('Message', {exact: true}).fill('Hi Alex,\n\nThanks for the notes. Everything is ready on our side.');
  await expect(page.locator('.composer .muted')).toHaveText('Saved on this device');
  await page.screenshot({path: info.outputPath(`ui-${theme}-desktop-compose.png`)});
  await page.getByRole('button', {name: 'Close', exact: true}).click();
  await page.getByRole('button', {name: 'Inbox', exact: true}).click();
  await page.locator('.message-row').first().click();
  await page.setViewportSize({width: 390, height: 844});
  await expect(page.getByRole('main', {name: 'Reading pane'})).toBeVisible();
  await expect(page.getByRole('region', {name: 'Message list'})).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  await page.screenshot({path: info.outputPath(`ui-${theme}-mobile-detail.png`)});
  await page.getByRole('button', {name: 'Back to messages', exact: true}).click();
  await expect(page.getByRole('region', {name: 'Message list'})).toBeVisible();
  await expect(page.getByRole('main', {name: 'Reading pane'})).toBeHidden();
  await page.screenshot({path: info.outputPath(`ui-${theme}-mobile-list.png`)});
  await page.getByRole('button', {name: 'Compose', exact: true}).click();
  await page.getByLabel('To', {exact: true}).fill('alex@inbox.test');
  await page.getByLabel('Subject', {exact: true}).fill('Following up');
  await page.getByLabel('Message', {exact: true}).fill('Hi Alex,\n\nThanks for the notes. Everything is ready on our side.');
  await expect(page.locator('.composer .muted')).toHaveText('Saved on this device');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path: info.outputPath(`ui-${theme}-mobile-compose.png`)});
  await page.getByRole('button', {name: 'Close', exact: true}).click();
  await expect(page.locator('.draft-link')).toHaveCount(2);
  await page.locator('.draft-link').last().click();
  await expect(page.getByLabel('Message', {exact: true})).toHaveValue(/^Hi Alex,/);
});
